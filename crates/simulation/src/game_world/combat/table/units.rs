const fn troop(
    kind: UnitKind,
    stats: (u16, u16, i16, u16),
    movement: (u32, u32),
    sight: (u8, u8, u8),
    price: (u32, u32, u32),
    seconds: u32,
) -> UnitCombat {
    UnitCombat {
        kind,
        hp: stats.0,
        attack: stats.1,
        melee_armour: stats.2,
        pierce_armour: stats.3,
        attack_kind: if matches!(
            kind,
            UnitKind::Crossbowman | UnitKind::EliteSkirmisher | UnitKind::Arbalester
        ) {
            DamageKind::Pierce
        } else {
            DamageKind::Melee
        },
        attack_period_centiseconds: movement.0,
        speed_hundredths: Some(movement.1),
        range: sight.0,
        min_range: sight.1,
        los: sight.2,
        training: Some(UnitTraining {
            cost: UnitCost {
                food: price.0,
                wood: price.1,
                gold: price.2,
                stone: 0,
            },
            seconds,
        }),
    }
}
