use super::*;

#[test]
fn compatibility_counts_never_accept_generated_or_unviable_entries_as_caught_controls() {
    assert!(counts_valid(3, 3, 0, 0, 0, 0, true));
    assert!(counts_valid(3, 0, 3, 0, 0, 0, false));
    for strong in [false, true] {
        for (total, caught, missed, timeout, unviable, success) in [
            (30, 30, 0, 0, 0, 0),
            (3, 0, 0, 0, 3, 0),
            (3, 0, 0, 0, 0, 3),
            (3, 2, 0, 1, 0, 0),
            (3, 1, 2, 0, 0, 0),
            (u64::MAX, u64::MAX, 0, 0, 0, 0),
        ] {
            assert!(!counts_valid(
                total, caught, missed, timeout, unviable, success, strong
            ));
        }
    }
    assert!(!counts_valid(3, 0, 3, 0, 0, 0, true));
    assert!(!counts_valid(3, 3, 0, 0, 0, 0, false));
}

#[test]
fn actual_fixture_lock_is_cargo_generated_before_real_commit_and_scope_admission() {
    for strong in [true, false] {
        let root = tempfile::tempdir().unwrap();
        fixture(root.path(), strong).unwrap();
        let lock = fs::read_to_string(root.path().join("Cargo.lock")).unwrap();
        assert!(lock.starts_with("# This file is automatically @generated by Cargo."));
        let oid = revision(root.path()).unwrap();
        assert!(matches!(oid.len(), 40 | 64));
        let snapshot = Snapshot::prepare_independent(root.path(), Kind::Commit(oid)).unwrap();
        assert!(snapshot.identity.clean_commit);
        assert_eq!(
            fs::read(root.path().join("Cargo.lock")).unwrap(),
            fs::read(snapshot.root().join("Cargo.lock")).unwrap()
        );
        for path in FILES {
            assert!(snapshot.root().join(path).is_file());
        }
        let tests =
            fs::read_to_string(snapshot.root().join("crates/harness/src/tests.rs")).unwrap();
        assert_eq!(tests.contains(TOKEN), strong);
        assert_eq!(
            tests.contains("deliberately_weak_temporary_control"),
            !strong
        );
        // This ordinary unit test exercises setup/admission, NOT cargo-mutants execution.
        snapshot.run_checked(|_| Ok(())).unwrap();
    }
}
