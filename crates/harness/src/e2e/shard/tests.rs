use super::Shard;
use super::balance::{assign, check_selection, records};
use std::collections::BTreeMap;

#[test]
fn shard_balance_is_longest_first_with_stable_ties_and_median_for_new_tests() {
    let tests = ["d", "c", "b", "a", "new"].map(str::to_owned);
    let weights = BTreeMap::from([
        ("a".into(), 8),
        ("b".into(), 6),
        ("c".into(), 4),
        ("d".into(), 2),
    ]);
    let plan = assign(&tests, &weights, 2).unwrap();
    // The median of 2, 4, 6, 8 is 5, so the new case precedes c and d.
    assert_eq!(plan, vec![vec!["a", "c"], vec!["b", "d", "new"]]);
    let mut reversed = tests.to_vec();
    reversed.reverse();
    assert_eq!(plan, assign(&reversed, &weights, 2).unwrap());
    assert!(assign(&["a".into(), "a".into()], &weights, 2).is_err());
    assert!(assign(&tests, &weights, 0).is_err());
}

#[test]
fn shard_selection_must_equal_the_assignment_including_multiplicity() {
    let expected = vec!["a".into(), "b".into()];
    assert!(check_selection(&expected, &["b".into(), "a".into()]).is_ok());
    for actual in [
        vec!["a".into()],
        vec!["a".into(), "c".into()],
        vec!["a".into(), "a".into(), "b".into()],
    ] {
        assert!(check_selection(&expected, &actual).is_err());
    }
}

#[test]
fn shard_report_identity_keeps_project_file_and_each_title_component() {
    let report = serde_json::json!({"errors": [], "suites": [{"title": "a.spec.ts", "specs": [], "suites": [{"title": "group", "specs": [{"file": "a.spec.ts", "title": "case", "tests": [{"projectName": "gpu", "results": [{"duration": 1499}]}]}]}]}]});
    let cases = records(&report).unwrap();
    assert_eq!(
        cases,
        vec![("[gpu] › a.spec.ts › group › case".into(), 1499)]
    );
    let mut invalid = report;
    invalid["errors"] = serde_json::json!([{"message": "load failed"}]);
    assert!(records(&invalid).is_err());
}

#[test]
fn shard_partition_covers_every_test_in_the_real_playwright_list_exactly_once() {
    // Generated by `make e2e-list` on Playwright 1.64.1, then e2e-durations --list.
    let report = serde_json::from_str(include_str!("list.json")).unwrap();
    let tests: Vec<_> = records(&report)
        .unwrap()
        .into_iter()
        .map(|(name, _)| name)
        .collect();
    let weights: BTreeMap<String, u64> =
        serde_json::from_str(include_str!("durations.json")).unwrap();
    // No fixed count: regenerating the fixture after adding a test must still pass.
    assert!(!tests.is_empty());
    assert!(tests.iter().all(|test| weights.contains_key(test)));
    for count in 1..=16 {
        let plan = assign(&tests, &weights, count).unwrap();
        let all: Vec<_> = plan.iter().flatten().cloned().collect();
        check_selection(&tests, &all).unwrap();
        let mut reversed = tests.clone();
        reversed.reverse();
        assert_eq!(plan, assign(&reversed, &weights, count).unwrap());
    }
    let loads: Vec<u64> = assign(&tests, &weights, 4)
        .unwrap()
        .iter()
        .map(|tests| tests.iter().map(|test| weights[test]).sum())
        .collect();
    assert!(
        loads.iter().max().unwrap() - loads.iter().min().unwrap() <= 1,
        "{loads:?}"
    );
}

#[test]
fn shard_equal_weights_and_empty_history_have_stable_title_and_shard_ties() {
    let tests = ["d", "b", "a", "c"].map(str::to_owned);
    assert_eq!(
        assign(&tests, &BTreeMap::new(), 2).unwrap(),
        vec![vec!["a", "c"], vec!["b", "d"]]
    );
}

#[test]
fn a_shard_is_i_of_n_within_bounds() {
    assert_eq!(Shard::parse("1/3"), Ok(Shard { index: 1, count: 3 }));
    assert_eq!(Shard::parse("3/3").map(|s| s.to_string()), Ok("3/3".into()));
    for invalid in [
        "", "0/3", "4/3", "1/0", "1/17", "1", "a/3", "1/b", "-1/3", "+1/3", "1/3/5", " 1/3",
    ] {
        assert!(Shard::parse(invalid).is_err(), "{invalid:?}");
    }
}

#[test]
fn no_shard_means_the_whole_suite_and_coverage_refuses_a_shard() {
    assert_eq!(Shard::select("", None), Ok(None));
    assert_eq!(Shard::select("", Some("1")), Ok(None));
    assert_eq!(
        Shard::select("2/3", None),
        Ok(Some(Shard { index: 2, count: 3 }))
    );
    assert!(Shard::select("2/3", Some("1")).is_err());
    assert!(Shard::select("9/3", None).is_err());
}
