//! Generate compact render tags from equivalent DAT animation descriptors.
use super::*;
pub(super) fn generate(selected: &[Selected], count: usize) -> Result<(), Error> {
    let base: Vec<_> = include_str!("scene_base.txt").lines().collect();
    let mut classes = BTreeMap::new();
    let mut canonical = Vec::new();
    let mut tags = Vec::new();
    let mut names = Vec::new();
    for pose in 0..count {
        let binding = bindings::BINDINGS.iter().find(|b| b.pose as usize == pose);
        let name = binding.map(|b| format!("{:?}", b.pose)).unwrap_or_else(|| {
            match pose {
                72 => "Arrow",
                73 => "Javelin",
                120 => "Stone",
                _ => "invalid",
            }
            .to_owned()
        });
        let name = match name.as_str() {
            "FishingShipStand" => "FishingShip".to_owned(),
            "FishingShipWalk" => "FishingShipMoving".to_owned(),
            "FishingShipWork" => "FishingShipWorking".to_owned(),
            "FisherWork" => "VillagerFishing".to_owned(),
            _ => name,
        };
        let key = if let Some(s) = selected.iter().find(|s| s.pose == pose) {
            format!(
                "{:?}:{}:{}:{}:{}:{}:{}",
                s.parts,
                s.frames,
                s.angles,
                s.seconds.to_bits(),
                s.replay.to_bits(),
                s.terminal,
                (42..46).contains(&pose)
            )
        } else {
            format!("projectile-{pose}")
        };
        let class = *classes.entry(key).or_insert_with(|| {
            canonical.push(pose);
            canonical.len() - 1
        });
        tags.push(class);
        names.push(name);
    }
    if base.len() + canonical.len() > 256 {
        return Err(invalid(
            "DE unit",
            0,
            format!(
                "native render tags exceed one byte: {} base + {} animations",
                base.len(),
                canonical.len()
            ),
        ));
    }
    let mut types = String::from(
        "//! Generated by make assets-unit-table-de. Compact semantic render tags.\n#[derive(Clone,Copy,Default,Debug,Eq,PartialEq)]\n#[repr(u8)]\npub enum SceneUnitKind {\n",
    );
    for (i, name) in base.iter().enumerate() {
        let _ = i;
        types.push_str(&format!("{name},\n"));
    }
    for class in 0..canonical.len() {
        if class == tags[70] {
            types.push_str("#[default]\n");
        }
        types.push_str(&format!("Actor{class},\n"));
    }
    types.push_str("}\n");
    let mut aliases = String::from(
        "//! Generated semantic aliases for equivalent native DAT graphics.\nuse super::SceneUnitKind;\n#[allow(non_upper_case_globals)]\nimpl SceneUnitKind {\n",
    );
    for (name, class) in names.iter().zip(&tags) {
        aliases.push_str(&format!("pub const {name}:Self=Self::Actor{class};\n"));
    }
    for (name, target) in [
        ("Scout", "ScoutStand"),
        ("Villager", "VillagerStand"),
        ("VillagerChopping", "ChopperWork"),
        ("VillagerCarryingWood", "CarryWood"),
        ("VillagerForaging", "ForagerWork"),
        ("VillagerCarryingFood", "CarryFood"),
        ("VillagerMiningGold", "MinerWork"),
        ("VillagerCarryingGold", "CarryGold"),
        ("VillagerMiningStone", "MinerWork"),
        ("VillagerCarryingStone", "CarryStone"),
        ("VillagerBuilding", "BuilderWork"),
    ] {
        aliases.push_str(&format!("pub const {name}:Self=Self::{target};\n"));
    }
    aliases.push_str("}\n");
    let mut map = format!(
        "//! Generated pose/tag projection; canonical slots share identical art.\nuse super::SceneUnitKind;\npub(super) const ACTORS:[SceneUnitKind;{count}]=[\n"
    );
    for class in tags {
        map.push_str(&format!("SceneUnitKind::Actor{class},\n"));
    }
    map.push_str("];\n");
    map.push_str(&format!(
        "pub(super) const BASE:usize={};\npub(super) const SLOTS:&[usize]=&{:?};\n",
        base.len(),
        canonical
    ));
    let root = "crates/rendering/src/game_renderer/scene_types";
    fs::write(format!("{root}/tags.rs"), types)?;
    fs::write(format!("{root}/aliases.rs"), aliases)?;
    fs::write(format!("{root}/actor_map.rs"), map)?;
    Ok(())
}
