/// Death and corpse poses of the Naval Warfare Overhaul ships.
pub(super) fn naval_decay_pair(pose: Pose) -> Option<(Pose, Pose)> {
    use Pose::*;
    [
        (FireGalleyDie, FireGalleyDecay),
        (FastFireShipDie, FastFireShipDecay),
        (DemolitionRaftDie, DemolitionRaftDecay),
        (HeavyDemolitionShipDie, HeavyDemolitionShipDecay),
        (GalleonDie, GalleonDecay),
        (CannonGalleonDie, CannonGalleonDecay),
        (EliteCannonGalleonDie, EliteCannonGalleonDecay),
        (HulkDie, HulkDecay),
        (WarHulkDie, WarHulkDecay),
        (CarrackDie, CarrackDecay),
        (CatapultGalleonDie, CatapultGalleonDecay),
    ]
    .into_iter()
    .find(|(die, decay)| pose == *die || pose == *decay)
}
