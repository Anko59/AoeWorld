#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum BuildingKind {
    TownCenter,
    House,
    LumberCamp,
    MiningCamp,
    Mill,
    Farm,
    Barracks,
    PalisadeWall,
    Outpost,
    Dock,
    ArcheryRange,
    Stable,
    Blacksmith,
    Market,
    WatchTower,
    PalisadeGate,
    Castle,
    Monastery,
    University,
    SiegeWorkshop,
    Bridge,
    StoneWall,
    StoneGate,
    Road,
    Wonder,
    FishTrap,
    GuardTower,
    Keep,
}
impl BuildingKind {
    pub const ALL: [Self; 28] = [
        Self::TownCenter,
        Self::House,
        Self::LumberCamp,
        Self::MiningCamp,
        Self::Mill,
        Self::Farm,
        Self::Barracks,
        Self::PalisadeWall,
        Self::Outpost,
        Self::Dock,
        Self::ArcheryRange,
        Self::Stable,
        Self::Blacksmith,
        Self::Market,
        Self::WatchTower,
        Self::PalisadeGate,
        Self::Castle,
        Self::Monastery,
        Self::University,
        Self::SiegeWorkshop,
        Self::Bridge,
        Self::StoneWall,
        Self::StoneGate,
        Self::Road,
        Self::Wonder,
        Self::FishTrap,
        Self::GuardTower,
        Self::Keep,
    ];
    pub const fn is_tower(self) -> bool {
        matches!(self, Self::WatchTower | Self::GuardTower | Self::Keep)
    }
    /// Footprint side in tiles; the single wire-level size table.
    pub const fn side(self) -> i32 {
        match self {
            Self::Wonder => 5,
            Self::TownCenter
            | Self::Market
            | Self::PalisadeGate
            | Self::StoneGate
            | Self::Castle
            | Self::University
            | Self::SiegeWorkshop => 4,
            Self::House | Self::LumberCamp | Self::MiningCamp | Self::Mill | Self::FishTrap => 2,
            Self::Farm
            | Self::Barracks
            | Self::Dock
            | Self::ArcheryRange
            | Self::Stable
            | Self::Blacksmith
            | Self::Monastery => 3,
            Self::PalisadeWall
            | Self::StoneWall
            | Self::Outpost
            | Self::WatchTower
            | Self::GuardTower
            | Self::Keep
            | Self::Bridge
            | Self::Road => 1,
        }
    }
    /// A one-tile wall segment, laid by dragging a line.
    pub const fn is_wall(self) -> bool {
        matches!(self, Self::PalisadeWall | Self::StoneWall)
    }
    pub const fn is_line(self) -> bool {
        self.is_wall() || matches!(self, Self::Road)
    }
    pub const fn is_gate(self) -> bool {
        matches!(self, Self::PalisadeGate | Self::StoneGate)
    }
    pub const fn depth(self) -> i32 {
        if matches!(self, Self::PalisadeGate | Self::StoneGate) {
            1
        } else {
            self.side()
        }
    }
}
